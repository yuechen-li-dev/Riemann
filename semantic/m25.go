func m25RadiusSlab(k int) rationalInterval {
	lo := big.NewRat(int64(35030+k), 10000)
	hi := new(big.Rat).Add(lo, big.NewRat(1, 10000))
	return ri(lo, hi)
}

// m25RootFunction is G=F0_t H-F0 H_t. Its zeros with H<0 are exactly the
// stationary points of M_r=F0/(-H). At a contact, G_t=H F_tt.
func m25RootFunction(r, t rationalInterval) (m23Jet, m23Jet) {
	box := [3]rationalInterval{riPoint(big.NewRat(0, 1)), r, t}
	q, h, _, _ := m23System(box)
	ht := q[1].d[0]
	g := m23Sub(m23Mul(q[1], h), m23Mul(q[0], m23Interval(ht)))
	return g, h
}

func m25ContactMass(r, t rationalInterval) (rationalInterval, error) {
	box := [3]rationalInterval{riPoint(big.NewRat(0, 1)), r, t}
	q, h, _, _ := m23System(box)
	if h.v.hi.Sign() >= 0 {
		return rationalInterval{}, fmt.Errorf("M25 B1 response is not strictly negative")
	}
	massJet := m23Div(q[0], m23Neg(h))
	center := [3]rationalInterval{riPoint(big.NewRat(0, 1)), riPoint(m25Mid(r)), riPoint(m25Mid(t))}
	qc, hc, _, _ := m23System(center)
	centerMass := m23Div(qc[0], m23Neg(hc)).v
	return m25CenteredRange(centerMass, massJet, box, 1, 2), nil
}

func m25Intersect(a, b rationalInterval) (rationalInterval, bool) {
	lo := new(big.Rat).Set(a.lo)
	if b.lo.Cmp(lo) > 0 {
		lo.Set(b.lo)
	}
	hi := new(big.Rat).Set(a.hi)
	if b.hi.Cmp(hi) < 0 {
		hi.Set(b.hi)
	}
	return ri(lo, hi), lo.Cmp(hi) <= 0
}

func m25Mid(x rationalInterval) *big.Rat {
	return new(big.Rat).Quo(new(big.Rat).Add(x.lo, x.hi), big.NewRat(2, 1))
}

func m25Radius(x rationalInterval) *big.Rat {
	return new(big.Rat).Quo(new(big.Rat).Sub(x.hi, x.lo), big.NewRat(2, 1))
}

func m25AbsUpper(x rationalInterval) *big.Rat {
	a := new(big.Rat).Abs(x.lo)
	b := new(big.Rat).Abs(x.hi)
	if b.Cmp(a) > 0 {
		return b
	}
	return a
}

func m25CenteredRange(center rationalInterval, jet m23Jet, box [3]rationalInterval, variables ...int) rationalInterval {
	err := big.NewRat(0, 1)
	for _, k := range variables {
		err.Add(err, new(big.Rat).Mul(m25AbsUpper(jet.d[k]), m25Radius(box[k])))
	}
	return ri(new(big.Rat).Sub(center.lo, err), new(big.Rat).Add(center.hi, err))
}

func m25EndpointRootRange(r rationalInterval, t *big.Rat) rationalInterval {
	tPoint := riPoint(t)
	full, _ := m25RootFunction(r, tPoint)
	centerR := riPoint(m25Mid(r))
	center, _ := m25RootFunction(centerR, tPoint)
	box := [3]rationalInterval{riPoint(big.NewRat(0, 1)), r, tPoint}
	return m25CenteredRange(center.v, full, box, 1)
}

func m25RoundPositiveOut(x rationalInterval, digits int) rationalInterval {
	scale := new(big.Int).Exp(big.NewInt(10), big.NewInt(int64(digits)), nil)
	roundDown := func(q *big.Rat) *big.Rat {
		n := new(big.Int).Mul(q.Num(), scale)
		v := new(big.Int).Quo(n, q.Denom())
		return new(big.Rat).SetFrac(v, scale)
	}
	roundUp := func(q *big.Rat) *big.Rat {
		n := new(big.Int).Mul(q.Num(), scale)
		n.Add(n, new(big.Int).Sub(q.Denom(), big.NewInt(1)))
		v := new(big.Int).Quo(n, q.Denom())
		return new(big.Rat).SetFrac(v, scale)
	}
	if x.lo.Sign() < 0 {
		panic("M25 positive outward rounding received a negative interval")
	}
	return ri(roundDown(x.lo), roundUp(x.hi))
}

func m25CInterval(m, r rationalInterval) rationalInterval {
	phase := riMul(riMul(m18Pi, riPoint(big.NewRat(1, 2))), r)
	a := m23TrigRange(phase, true)
	return riAdd(m24C0(), riMul(riMul(riMul(m18Pi, riPoint(big.NewRat(1, 2))), m), a))
}

func m25EnvelopeSecond(box [3]rationalInterval) rationalInterval {
	q, h, hr, _ := m23System(box)
	mp := riNeg(riMul(riMul(box[0], hr.v), riReciprocal(h.v)))
	tp := riNeg(riMul(riAdd(riMul(q[1].d[0], mp), q[1].d[1]), riReciprocal(q[1].d[2])))
	gp := riAdd(q[2].d[1], riMul(q[2].d[2], tp))
	return riMul(riMul(riMul(riMul(m18Pi, riPoint(big.NewRat(1, 2))), box[0]), gp), riReciprocal(h.v))
}

func m25OriginLower(m, r rationalInterval) rationalInterval {
	piHalf := riMul(m18Pi, riPoint(big.NewRat(1, 2)))
	phase := riMul(piHalf, r)
	cp, sp := m23TrigRange(phase, true), m23TrigRange(phase, false)
	w0 := riAdd(riSub(riReciprocal(m18Pi), riMul(riPoint(big.NewRat(4, 1)), riPow(m18Pi, -2))), riMul(riPoint(big.NewRat(8, 1)), riPow(m18Pi, -3)))
	w := riAdd(w0, riMul(m, riSub(riMul(riPoint(big.NewRat(2, 1)), riMul(cp, riReciprocal(m18Pi))), riMul(r, sp))))
	c := m25CInterval(m, r)
	// On 0<=t<=1/2: 1+2(cos(t)-1)/t^2>=0, sinc(t)<=1,
	// cos(t)>=1-t^2/2, and cos(rt)>=1-(rt)^2/2.
	t := big.NewRat(1, 2)
	cosT := riPoint(new(big.Rat).Sub(big.NewRat(1, 1), new(big.Rat).Quo(new(big.Rat).Mul(t, t), big.NewRat(2, 1))))
	rt := riMul(r, riPoint(t))
	cosRT := riSub(riPoint(big.NewRat(1, 1)), riMul(riMul(rt, rt), riPoint(big.NewRat(1, 2))))
	return riAdd(riMul(riPoint(big.NewRat(2, 1)), riSub(riPoint(big.NewRat(1, 1)), c)), riAdd(riMul(riMul(riPoint(big.NewRat(2, 1)), w), cosT), riMul(riMul(riPoint(big.NewRat(2, 1)), m), cosRT)))
}

func m25StrictCompact(m, r rationalInterval) (rationalInterval, error) {
	pieces := [][2]*big.Rat{
		{big.NewRat(1, 2), big.NewRat(156, 100)},
		{big.NewRat(158, 100), big.NewRat(178, 100)},
		{big.NewRat(181, 100), big.NewRat(4, 1)},
	}
	step := big.NewRat(1, 50)
	best := riPoint(big.NewRat(1, 1))
	for _, piece := range pieces {
		for left := new(big.Rat).Set(piece[0]); left.Cmp(piece[1]) < 0; left.Add(left, step) {
			right := new(big.Rat).Add(left, step)
			if right.Cmp(piece[1]) > 0 {
				right = new(big.Rat).Set(piece[1])
			}
			tCell := ri(new(big.Rat).Set(left), right)
			box := [3]rationalInterval{m, r, tCell}
			q, _, _, _ := m23System(box)
			centerQ, _, _, _ := m23System([3]rationalInterval{m, r, riPoint(m25Mid(tCell))})
			value := m25CenteredRange(centerQ[0].v, q[0], box, 2)
			if value.lo.Sign() <= 0 {
				return rationalInterval{}, fmt.Errorf("M25 strict compact cell [%s,%s] failed: %s", left, right, m23Decimal(value.lo))
			}
			if value.lo.Cmp(best.lo) < 0 {
				best = value
			}
		}
	}
	return best, nil
}

func m25StrictCompactBranchWindow(m, r, contact, centerMass, centerRadius rationalInterval) (rationalInterval, error) {
	type piece struct{ left, right, step *big.Rat }
	pieces := []piece{
		{big.NewRat(1, 2), big.NewRat(6, 5), big.NewRat(1, 50)},
		{big.NewRat(6, 5), big.NewRat(154, 100), big.NewRat(1, 4000)},
		{big.NewRat(165, 100), big.NewRat(170, 100), big.NewRat(1, 2000)},
		{big.NewRat(190, 100), big.NewRat(2, 1), big.NewRat(1, 2000)},
		{big.NewRat(2, 1), big.NewRat(4, 1), big.NewRat(1, 50)},
	}
	best := riPoint(big.NewRat(1, 1))
	_, contactH, contactHr, _ := m23System([3]rationalInterval{m, r, contact})
	mp := riNeg(riMul(riMul(m, contactHr.v), riReciprocal(contactH.v)))
	for _, piece := range pieces {
		for left := new(big.Rat).Set(piece.left); left.Cmp(piece.right) < 0; left.Add(left, piece.step) {
			right := new(big.Rat).Add(left, piece.step)
			if right.Cmp(piece.right) > 0 {
				right = new(big.Rat).Set(piece.right)
			}
			tCell := ri(new(big.Rat).Set(left), right)
			tCenter := riPoint(m25Mid(tCell))
			fullQ, _, _, _ := m23System([3]rationalInterval{m, r, tCell})
			centerQ, _, _, _ := m23System([3]rationalInterval{centerMass, centerRadius, tCenter})
			dr := riAdd(fullQ[0].d[1], riMul(fullQ[0].d[0], mp))
			distance := maxRat(new(big.Rat).Abs(new(big.Rat).Sub(r.lo, centerRadius.hi)), new(big.Rat).Abs(new(big.Rat).Sub(r.hi, centerRadius.lo)))
			errR := new(big.Rat).Mul(m25AbsUpper(dr), distance)
			errT := new(big.Rat).Mul(m25AbsUpper(fullQ[0].d[2]), m25Radius(tCell))
			err := new(big.Rat).Add(errR, errT)
			value := ri(new(big.Rat).Sub(centerQ[0].v.lo, err), new(big.Rat).Add(centerQ[0].v.hi, err))
			if value.lo.Sign() <= 0 {
				return rationalInterval{}, fmt.Errorf("M25 centered branch cell [%s,%s] failed: %s", left, right, m23Decimal(value.lo))
			}
			if value.lo.Cmp(best.lo) < 0 {
				best = value
			}
		}
	}
	return best, nil
}

